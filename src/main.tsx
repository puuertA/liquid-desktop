import React from 'react';
import {createRoot} from 'react-dom/client';
import {widgetIds, type WidgetId} from './types';
import {Panel} from './panel/Panel';
import {WidgetWindow} from './widgets/WidgetWindow';
import {MaterialLab} from './glass/MaterialLab';
import {Island} from './island/Island';
import {TopBar} from './topbar/TopBar';
import {FusionWindow} from './fusion/FusionWindow';
import {ControlCenter} from './control-center/ControlCenter';
import {FusionLab} from './fusion/FusionLab';
import './style.css';
import './widgets/widgets.css';
import './widgets/collection.css';
import './widgets/collection-enhancements.css';
import './panel/panel.css';
import './panel/redesign.css';
const selected = new URLSearchParams(location.search).get('widget');
const id = widgetIds.includes(selected as WidgetId) ? selected as WidgetId : null;
const island=new URLSearchParams(location.search).get('surface')==='island';
const topbar=new URLSearchParams(location.search).get('surface')==='topbar';
const fusion=new URLSearchParams(location.search).get('surface')==='fusion';
const center=new URLSearchParams(location.search).get('surface')==='control-center';
document.documentElement.dataset.surface = center?'control-center':fusion?'fusion':topbar?'topbar':island?'island':id ? 'widget' : 'panel';
const lab=import.meta.env.DEV&&new URLSearchParams(location.search).get('studio')==='materials';
const fusionLab=import.meta.env.DEV&&new URLSearchParams(location.search).get('studio')==='fusion';
createRoot(document.getElementById('root')!).render(<React.StrictMode>{fusionLab?<FusionLab/>:lab?<MaterialLab/>:center?<ControlCenter/>:fusion?<FusionWindow/>:topbar?<TopBar/>:island?<Island/>:id?<WidgetWindow id={id}/>:<Panel/>}</React.StrictMode>);
